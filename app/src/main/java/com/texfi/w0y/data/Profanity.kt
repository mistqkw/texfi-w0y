package com.texfi.w0y.data

import java.util.Locale

/**
 * Словарь мата для режима «без мата».
 *
 * Корни, а не слова целиком: русский мат склоняется и обрастает
 * приставками, перечислить все формы невозможно. Отсюда и неточность —
 * режим честно помечен бетой, и он приглушает строку, а не слово: вырезать
 * отдельное слово из готовой записи нельзя, для этого нужна дорожка без
 * вокала, которой у нас нет.
 */
object Profanity {
    private val roots =
        listOf(
            "хуй", "хуя", "хуе", "хую", "хуё", "хуи",
            "бляд", "блять", "бля́",
            "ебат", "ебал", "ебан", "ебуч", "ебло", "ёбан", "ебен", "заеб", "наеб", "уеб", "поеб",
            "пизд",
            "сука", "суки", "суке", "сучар", "сучк",
            "мудак", "мудил", "мудо",
            "гандон", "гондон",
            "залуп", "дроч", "пидор", "пидар", "пидр",
            "ублюдок", "нахуй", "похуй", "охуе", "охуи", "хуёв", "хуев",
            "fuck", "shit", "bitch", "cunt", "nigga", "whore", "asshole", "motherf",
        )

    /** Есть ли в строке мат. */
    fun inText(text: String): Boolean {
        val lower = text.lowercase(Locale.ROOT).replace('ё', 'е')
        return roots.any { root -> lower.contains(root.replace('ё', 'е')) }
    }
}
